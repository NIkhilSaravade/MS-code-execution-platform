"""LLM-as-judge: a second, independent LLM call scores a generated review
(not the submitted code) against a fixed rubric. Deliberately a separate
prompt/call from the reviewer agent itself - the reviewer shouldn't grade
its own homework."""

import json
import re

from pydantic import BaseModel, ValidationError

from services.llm_provider import FALLBACK_MODEL_NAME, MODEL_NAME, _completion_with_rate_limit_retry

JUDGE_PROMPT = """You are grading a code review that was generated by an AI reviewer for a
competitive-programming submission. Score it on three axes, each 1-5 (5 = best):

- helpfulness: would this genuinely help the author understand/fix the issue?
- accuracy: are the specific claims made (about the bug, complexity, etc.) actually correct?
- actionability: does it give a concrete, specific next step, not vague generic advice?

Problem:
{problem}

Submitted code:
{code}

Generated review (JSON):
{review}

Respond with ONLY this JSON, no commentary:
{{"helpfulness": <1-5>, "accuracy": <1-5>, "actionability": <1-5>, "rationale": "<one sentence>"}}
"""


class JudgeScore(BaseModel):
    helpfulness: int
    accuracy: int
    actionability: int
    rationale: str


def _clean(text: str) -> str:
    cleaned = re.sub(r"```json", "", text, flags=re.IGNORECASE)
    cleaned = re.sub(r"```", "", cleaned)
    match = re.search(r"\{.*\}", cleaned, re.DOTALL)
    return match.group(0) if match else cleaned.strip()


def judge_review(problem_description: str, code: str, review: dict) -> JudgeScore:
    prompt = JUDGE_PROMPT.format(problem=problem_description, code=code, review=json.dumps(review))
    response = _completion_with_rate_limit_retry(
        model=MODEL_NAME,
        messages=[{"role": "user", "content": prompt}],
        temperature=0.0,
        fallbacks=[FALLBACK_MODEL_NAME],
    )
    raw = response.choices[0].message.content
    try:
        return JudgeScore.model_validate_json(_clean(raw))
    except (json.JSONDecodeError, ValidationError) as exc:
        raise ValueError(f"Judge output failed to parse: {exc}. Raw: {raw!r}") from exc
